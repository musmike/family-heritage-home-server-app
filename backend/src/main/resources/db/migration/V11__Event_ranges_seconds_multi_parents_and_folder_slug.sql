-- V11__Event_ranges_seconds_multi_parents_and_folder_slug.sql

-- 1. Add seconds to date_descriptors
ALTER TABLE date_descriptors
    ADD COLUMN IF NOT EXISTS start_second INT,
    ADD COLUMN IF NOT EXISTS end_second INT;

-- 2. Add custom folder slug to events
ALTER TABLE events
    ADD COLUMN IF NOT EXISTS folder_slug VARCHAR(255);

-- 3. Create ordered many-to-many parent-child relationship table for events
CREATE TABLE IF NOT EXISTS event_parent_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_event_id BIGINT NOT NULL,
    parent_event_id BIGINT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,

    UNIQUE (child_event_id, parent_event_id),
    CONSTRAINT fk_epl_child_event FOREIGN KEY (child_event_id) REFERENCES events(id) ON DELETE CASCADE,
    CONSTRAINT fk_epl_parent_event FOREIGN KEY (parent_event_id) REFERENCES events(id) ON DELETE CASCADE,
    CONSTRAINT chk_epl_not_self CHECK (child_event_id <> parent_event_id)
);

CREATE INDEX IF NOT EXISTS idx_epl_child_event_id ON event_parent_links (child_event_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_epl_parent_event_id ON event_parent_links (parent_event_id);

-- Migrate existing single parent_event_id links into event_parent_links as first parent (sort_order = 0)
INSERT INTO event_parent_links (child_event_id, parent_event_id, sort_order)
SELECT id, parent_event_id, 0
FROM events
WHERE parent_event_id IS NOT NULL
ON CONFLICT (child_event_id, parent_event_id) DO NOTHING;

-- 4. Add metadata date descriptor and metadata tag source to media_items
ALTER TABLE media_items
    ADD COLUMN IF NOT EXISTS metadata_date_descriptor_id BIGINT,
    ADD COLUMN IF NOT EXISTS metadata_date_source VARCHAR(120),
    ADD CONSTRAINT fk_media_items_metadata_date FOREIGN KEY (metadata_date_descriptor_id)
        REFERENCES date_descriptors(id) ON DELETE SET NULL;