                                             CONSTRAINT fk_attribute_dictionary_values_attribute_definition FOREIGN KEY (attribute_definition_id)
                                                 REFERENCES attribute_definitions(id) ON DELETE CASCADE
);

CREATE INDEX idx_attribute_dictionary_values_definition_id ON attribute_dictionary_values (attribute_definition_id);


CREATE TABLE event_attribute_values (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
