CREATE TABLE person_names (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              person_id BIGINT NOT NULL,
                              type VARCHAR(50) NOT NULL,
                              given_name VARCHAR(255),
                              surname VARCHAR(200),
                              is_current BOOLEAN NOT NULL,

                              CONSTRAINT fk_person_names_person FOREIGN KEY (person_id)
                                  REFERENCES people(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ux_person_names_current
    ON person_names (person_id)
    WHERE is_current = true;

CREATE INDEX idx_person_names_person_id ON person_names (person_id);


CREATE TABLE families (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          husband_id BIGINT,
                          wife_id BIGINT,
                          primary_wedding_id BIGINT,
                          status_id BIGINT NOT NULL,

                          CONSTRAINT at_least_one_parent CHECK (
                              husband_id IS NOT NULL OR wife_id IS NOT NULL
                              ),
                          CONSTRAINT fk_families_husband FOREIGN KEY (husband_id)
                              REFERENCES people(id),
                          CONSTRAINT fk_families_wife FOREIGN KEY (wife_id)
                              REFERENCES people(id),
                          CONSTRAINT fk_families_primary_wedding FOREIGN KEY (primary_wedding_id)
                              REFERENCES events(id),
                          CONSTRAINT fk_families_status FOREIGN KEY (status_id) REFERENCES user_codes(id)
);

CREATE INDEX idx_families_husband_id ON families (husband_id);
CREATE INDEX idx_families_wife_id ON families (wife_id);


CREATE TABLE family_external_ids (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     family_id BIGINT NOT NULL,
                                     uid_value VARCHAR(100) NOT NULL UNIQUE,
                                     source_system VARCHAR(100),

                                     CONSTRAINT fk_family_external_ids_family FOREIGN KEY (family_id)
                                         REFERENCES families(id) ON DELETE CASCADE
);

CREATE INDEX idx_family_external_ids_family_id ON family_external_ids (family_id);


CREATE TABLE family_children (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 family_id BIGINT NOT NULL,
                                 child_id BIGINT NOT NULL,
                                 father_relationship_type VARCHAR(50) NOT NULL,
                                 mother_relationship_type VARCHAR(50) NOT NULL,

                                 UNIQUE(family_id, child_id),
                                 CONSTRAINT fk_family_children_family FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE,
                                 CONSTRAINT fk_family_children_child FOREIGN KEY (child_id) REFERENCES people(id) ON DELETE CASCADE
);

CREATE INDEX idx_family_children_child_id ON family_children (child_id);
CREATE INDEX idx_family_children_family_id ON family_children (family_id);


