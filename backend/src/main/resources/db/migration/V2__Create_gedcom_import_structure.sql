CREATE TABLE user_codes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            category VARCHAR(100) NOT NULL,
                            code VARCHAR(100) NOT NULL,
                            is_system BOOLEAN DEFAULT FALSE,

                            UNIQUE(category, code)
);


CREATE TABLE translations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              table_name VARCHAR(70) NOT NULL,
                              record_id BIGINT NOT NULL,
                              field_name VARCHAR(70) NOT NULL,
                              language_code VARCHAR(10) NOT NULL,
                              value VARCHAR(255) NOT NULL,

                              UNIQUE(table_name, record_id, field_name, language_code)
);

CREATE INDEX idx_translations_lookup
    ON translations(table_name, record_id, field_name, language_code);


CREATE TABLE date_descriptors (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  date_type VARCHAR(50) NOT NULL,

                                  free_text VARCHAR(255),

                                  start_qualifier VARCHAR(50),
                                  start_year INT,
                                  start_month INT,
                                  start_day INT,

                                  end_qualifier VARCHAR(50),
                                  end_year INT,
                                  end_month INT,
                                  end_day INT,

                                  sort_date_time_min TIMESTAMP,
                                  sort_date_time_max TIMESTAMP
);

CREATE INDEX idx_dd_sort_min  ON date_descriptors (sort_date_time_min);
CREATE INDEX idx_dd_sort_max  ON date_descriptors (sort_date_time_max);
CREATE INDEX idx_dd_date_type ON date_descriptors (date_type);


CREATE TABLE locations (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name VARCHAR(255) NOT NULL UNIQUE
);


CREATE TABLE events (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        type_id BIGINT NOT NULL,
                        cached_start_sort_date_time TIMESTAMP,
                        cached_end_sort_date_time TIMESTAMP,
                        start_date_id BIGINT,
                        end_date_id BIGINT,
                        main_location_id BIGINT,

                        CONSTRAINT fk_events_type FOREIGN KEY (type_id) REFERENCES user_codes(id),
                        CONSTRAINT fk_events_start_date FOREIGN KEY (start_date_id) REFERENCES date_descriptors(id),
                        CONSTRAINT fk_events_end_date FOREIGN KEY (end_date_id) REFERENCES date_descriptors(id),
                        CONSTRAINT fk_events_main_location FOREIGN KEY (main_location_id) REFERENCES locations(id) ON DELETE SET NULL
);


CREATE TABLE people (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        cached_given_name VARCHAR(255),
                        cached_surname VARCHAR(255),
                        sex VARCHAR(20),
                        life_state VARCHAR(20),
                        is_archived BOOLEAN NOT NULL DEFAULT FALSE,
                        birth_event_id BIGINT,
                        death_event_id BIGINT,

                        CONSTRAINT fk_people_birth_event FOREIGN KEY (birth_event_id)
                            REFERENCES events(id) ON DELETE SET NULL,
                        CONSTRAINT fk_people_death_event FOREIGN KEY (death_event_id)
                            REFERENCES events(id) ON DELETE SET NULL
);

CREATE INDEX idx_people_is_archived ON people (is_archived);


CREATE TABLE person_external_ids (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     person_id BIGINT NOT NULL,
                                     uid_value VARCHAR(100) NOT NULL UNIQUE,
                                     source_system VARCHAR(100),

                                     CONSTRAINT fk_person_external_ids_person FOREIGN KEY (person_id)
                                         REFERENCES people(id) ON DELETE CASCADE
);

CREATE INDEX idx_person_external_ids_person_id ON person_external_ids (person_id);


CREATE TABLE person_gedcom_data (
