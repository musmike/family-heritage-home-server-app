-- 1. Add source_text and inscription_text (reverse-side signature/inscription) to media_items
ALTER TABLE media_items
    ADD COLUMN IF NOT EXISTS source_text VARCHAR(500),
    ADD COLUMN IF NOT EXISTS inscription_text TEXT;

-- 2. Create media_person_links supporting DEPICTED, RELATED, and AUTHOR (both DB person and text-only)
CREATE TABLE IF NOT EXISTS media_person_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    person_id BIGINT,
    person_text VARCHAR(255),
    person_sex VARCHAR(20),
    link_type VARCHAR(30) NOT NULL DEFAULT 'DEPICTED',

    CONSTRAINT fk_mpl_media FOREIGN KEY (media_id) REFERENCES media_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_mpl_person FOREIGN KEY (person_id) REFERENCES people(id) ON DELETE CASCADE,
    CONSTRAINT chk_mpl_person_or_text CHECK (person_id IS NOT NULL OR person_text IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_mpl_media_id ON media_person_links (media_id);
CREATE INDEX IF NOT EXISTS idx_mpl_person_id ON media_person_links (person_id);

-- Migrate existing media_persons rows as DEPICTED
INSERT INTO media_person_links (media_id, person_id, link_type)
SELECT mp.media_id, mp.person_id, 'DEPICTED'
FROM media_persons mp
WHERE NOT EXISTS (
    SELECT 1 FROM media_person_links mpl
    WHERE mpl.media_id = mp.media_id
      AND mpl.person_id = mp.person_id
      AND mpl.link_type = 'DEPICTED'
);

-- 3. Create media_versions table (for Original, Restored, Colorized, Reverse side, etc.)
CREATE TABLE IF NOT EXISTS media_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    version_type VARCHAR(40) NOT NULL,
    version_label VARCHAR(150) NOT NULL,
    relative_path VARCHAR(700) NOT NULL UNIQUE,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    is_main BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_mv_media FOREIGN KEY (media_id) REFERENCES media_items(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_mv_media_id ON media_versions (media_id);