-- V4__Add_proband_user_person_and_activity_logs.sql

ALTER TABLE people
    ADD COLUMN IF NOT EXISTS is_default_proband BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS person_id BIGINT,
    ADD CONSTRAINT fk_users_person FOREIGN KEY (person_id)
        REFERENCES people(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_type VARCHAR(50) NOT NULL,
    actor_username VARCHAR(255) NOT NULL,
    description VARCHAR(500) NOT NULL,
    target_type VARCHAR(50),
    target_id BIGINT,
    ip_address VARCHAR(64),
    admin_only BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_activity_logs_created_at ON activity_logs (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_activity_logs_action_type ON activity_logs (action_type);