-- 1. Ordered many-to-many link between media_items and media_collections
CREATE TABLE IF NOT EXISTS media_collection_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    collection_id BIGINT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    UNIQUE (media_id, collection_id),
    CONSTRAINT fk_mcl_media FOREIGN KEY (media_id) REFERENCES media_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_mcl_collection FOREIGN KEY (collection_id) REFERENCES media_collections(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_mcl_media_id ON media_collection_links(media_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_mcl_collection_id ON media_collection_links(collection_id);

-- Migrate existing single collection_id links as primary collection (sort_order = 0)
INSERT INTO media_collection_links (media_id, collection_id, sort_order)
SELECT id, collection_id, 0
FROM media_items
WHERE collection_id IS NOT NULL
ON CONFLICT (media_id, collection_id) DO NOTHING;

-- 2. Ordered many-to-many link between undated events and media_collections
CREATE TABLE IF NOT EXISTS event_collection_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    collection_id BIGINT NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    UNIQUE (event_id, collection_id),
    CONSTRAINT fk_ecl_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
    CONSTRAINT fk_ecl_collection FOREIGN KEY (collection_id) REFERENCES media_collections(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_ecl_event_id ON event_collection_links(event_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_ecl_collection_id ON event_collection_links(collection_id);