CREATE TABLE IF NOT EXISTS media_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    founder_person_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_media_collections_founder FOREIGN KEY (founder_person_id)
        REFERENCES people(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS media_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_type VARCHAR(30) NOT NULL,
    primary_context VARCHAR(50) NOT NULL,
    relative_path VARCHAR(700) NOT NULL UNIQUE,
    file_name VARCHAR(255) NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    title VARCHAR(255),
    description TEXT,
    date_descriptor_id BIGINT,
    collection_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_media_items_date FOREIGN KEY (date_descriptor_id)
        REFERENCES date_descriptors(id) ON DELETE SET NULL,
    CONSTRAINT fk_media_items_collection FOREIGN KEY (collection_id)
        REFERENCES media_collections(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_media_items_context ON media_items (primary_context);

CREATE TABLE IF NOT EXISTS media_persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    person_id BIGINT NOT NULL,

    UNIQUE(media_id, person_id),
    CONSTRAINT fk_media_persons_media FOREIGN KEY (media_id)
        REFERENCES media_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_media_persons_person FOREIGN KEY (person_id)
        REFERENCES people(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_media_persons_person_id ON media_persons (person_id);

CREATE TABLE IF NOT EXISTS media_graves (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    grave_id BIGINT NOT NULL,

    UNIQUE(media_id, grave_id),
    CONSTRAINT fk_media_graves_media FOREIGN KEY (media_id)
        REFERENCES media_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_media_graves_grave FOREIGN KEY (grave_id)
        REFERENCES graves(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_media_graves_grave_id ON media_graves (grave_id);

CREATE TABLE IF NOT EXISTS media_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL,

    UNIQUE(media_id, event_id),
    CONSTRAINT fk_media_events_media FOREIGN KEY (media_id)
        REFERENCES media_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_media_events_event FOREIGN KEY (event_id)
        REFERENCES events(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_media_events_event_id ON media_events (event_id);

ALTER TABLE people
    ADD COLUMN IF NOT EXISTS avatar_media_id BIGINT,
    ADD CONSTRAINT fk_people_avatar_media FOREIGN KEY (avatar_media_id)
        REFERENCES media_items(id) ON DELETE SET NULL;

ALTER TABLE graves
    ADD COLUMN IF NOT EXISTS primary_media_id BIGINT,
    ADD CONSTRAINT fk_graves_primary_media FOREIGN KEY (primary_media_id)
        REFERENCES media_items(id) ON DELETE SET NULL;