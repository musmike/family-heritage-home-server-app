-- V5__Redesign_cemeteries_graves_and_burials.sql

CREATE TABLE IF NOT EXISTS cemeteries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    management_type VARCHAR(50),
    denomination VARCHAR(50),
    description TEXT,
    location_id BIGINT,

    CONSTRAINT fk_cemeteries_location FOREIGN KEY (location_id)
        REFERENCES locations(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_cemeteries_location_id ON cemeteries (location_id);

ALTER TABLE burials
    ADD COLUMN IF NOT EXISTS place_description VARCHAR(500);

-- Copy existing GEDCOM burial location names into burials.place_description before dropping cemetery_location_id
UPDATE burials b
SET place_description = l.name
FROM graves g
         JOIN locations l ON g.cemetery_location_id = l.id
WHERE b.grave_id = g.id
  AND b.place_description IS NULL;

-- Remove locations from BURIAL events
DELETE FROM event_locations el
    USING events e, user_codes uc
WHERE el.event_id = e.id
  AND e.type_id = uc.id
  AND uc.category = 'EVENT_TYPE'
  AND uc.code = 'BURIAL';

UPDATE events e
SET main_location_id = NULL
FROM user_codes uc
WHERE e.type_id = uc.id
  AND uc.category = 'EVENT_TYPE'
  AND uc.code = 'BURIAL';

ALTER TABLE graves
    DROP CONSTRAINT IF EXISTS fk_graves_cemetery_location,
    DROP COLUMN IF EXISTS cemetery_location_id,
    ADD COLUMN IF NOT EXISTS cemetery_id BIGINT,
    ADD COLUMN IF NOT EXISTS section VARCHAR(100),
    ADD COLUMN IF NOT EXISTS sector VARCHAR(100),
    ADD COLUMN IF NOT EXISTS row_number VARCHAR(100),
    ADD COLUMN IF NOT EXISTS grave_number VARCHAR(100),
    ADD COLUMN IF NOT EXISTS grave_type VARCHAR(50),
    ADD COLUMN IF NOT EXISTS description TEXT,
    ADD COLUMN IF NOT EXISTS epitaph TEXT,
    ADD CONSTRAINT fk_graves_cemetery FOREIGN KEY (cemetery_id)
        REFERENCES cemeteries(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_graves_cemetery_id ON graves (cemetery_id);

-- Clean up any orphan locations that were previously used only as burial/cemetery places
DELETE FROM locations l
WHERE NOT EXISTS (SELECT 1 FROM event_locations el WHERE el.location_id = l.id)
  AND NOT EXISTS (SELECT 1 FROM events e WHERE e.main_location_id = l.id)
  AND NOT EXISTS (SELECT 1 FROM cemeteries c WHERE c.location_id = l.id);
